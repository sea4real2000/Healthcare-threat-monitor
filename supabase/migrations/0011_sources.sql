-- 0011_sources.sql
-- Plugging in a hospital's own data without programming: a setup wizard for the inventory,
-- read only connections to patient record databases, and uploads of exported access reports.
-- Safe to run more than once.

-- The collector a hospital installation's background service signs as. Its secret is derived from
-- INGEST_SIGNING_KEY like every other collector. It cannot act on endpoints.
insert into collectors (id, name, can_respond) values
  ('hospital_service', 'Hospital installation background service', false),
  ('console_upload', 'Reports uploaded in the console', false)
on conflict (id) do nothing;

-- A read only connection to a patient record database. The password is encrypted with
-- SOURCES_SECRET, which only the console and the background service hold.
create table if not exists record_sources (
  id bigint generated always as identity primary key,
  name text not null,
  kind text not null check (kind in ('postgres', 'mysql')),
  host text not null,
  port integer not null check (port between 1 and 65535),
  database_name text not null,
  username text not null,
  password_sealed text not null,
  encrypt boolean not null default true,
  timezone text not null default 'UTC',
  day_first boolean not null default true,
  state text not null default 'setup' check (state in ('setup', 'active', 'paused')),
  pending text check (pending in ('discover', 'preview', 'activate')),
  tables jsonb not null default '[]'::jsonb,
  table_name text,
  columns jsonb not null default '[]'::jsonb,
  preview jsonb not null default '[]'::jsonb,
  mapping jsonb not null default '{}'::jsonb,
  backfill_days integer not null default 7 check (backfill_days between 0 and 365),
  checkpoint jsonb,
  last_error text,
  last_error_at timestamptz,
  last_ok_at timestamptz,
  last_rows integer not null default 0,
  total_rows bigint not null default 0,
  rejected_rows bigint not null default 0,
  created_at timestamptz not null default now(),
  created_by text,
  updated_at timestamptz not null default now()
);

-- An exported access report uploaded in the console. The file itself is deleted once imported.
create table if not exists record_uploads (
  id bigint generated always as identity primary key,
  filename text not null,
  size_bytes integer not null,
  content bytea,
  headers jsonb not null default '[]'::jsonb,
  preview jsonb not null default '[]'::jsonb,
  row_count integer not null default 0,
  mapping jsonb not null default '{}'::jsonb,
  timezone text not null default 'UTC',
  day_first boolean not null default true,
  status text not null default 'mapping' check (status in ('mapping', 'imported', 'discarded')),
  accepted integer not null default 0,
  duplicate integer not null default 0,
  rejected integer not null default 0,
  problems jsonb not null default '[]'::jsonb,
  uploaded_by text,
  uploaded_at timestamptz not null default now(),
  imported_at timestamptz
);

-- The result of the most recent spreadsheet import into the inventory, per kind.
create table if not exists inventory_imports (
  id bigint generated always as identity primary key,
  kind text not null check (kind in ('departments', 'staff', 'assets', 'patients')),
  filename text,
  status text not null check (status in ('imported', 'refused')),
  rows integer not null default 0,
  problems jsonb not null default '[]'::jsonb,
  imported_by text,
  imported_at timestamptz not null default now()
);

